"""Generate tmem.cu: tcgen05.ld / tcgen05.st cost per shape and repeat count.

The asm operand list grows with the repeat count, so the kernels are emitted
from this script: python -m megabench.primbench.gen_tmem > megabench/primbench/tmem.cu
"""

from __future__ import annotations

# (shape, 32-bit registers per thread at .x1, max repeat)
SHAPES = (("32x32b", 1, 128), ("16x64b", 1, 128), ("16x128b", 2, 64), ("16x256b", 4, 32))
# Bytes each warp moves per .x1: 32x32b = 32 lanes x 4 B, 16x64b = 16 x 8 B,
# 16x128b = 16 x 16 B, 16x256b = 16 x 32 B.
WARP_BYTES = {"32x32b": 128, "16x64b": 128, "16x128b": 256, "16x256b": 512}


def reps(limit: int):
    n = 1
    while n <= limit:
        yield n
        n *= 2


def kernel(shape: str, per: int, x: int) -> str:
    n = per * x
    regs = ",".join(f"%{i}" for i in range(n))
    outs = ", ".join(f'"=r"(v[{i}])' for i in range(n))
    ins = ", ".join(f'"r"(v[{i}])' for i in range(n))
    name = f"{shape.replace('x', '_')}_x{x}"
    return f"""
__device__ __forceinline__ void ld_{name}(uint32_t t, uint32_t* v) {{
  asm volatile("tcgen05.ld.sync.aligned.{shape}.x{x}.b32 {{{regs}}}, [%{n}];" : {outs} : "r"(t));
}}
__device__ __forceinline__ void st_{name}(uint32_t t, const uint32_t* v) {{
  asm volatile("tcgen05.st.sync.aligned.{shape}.x{x}.b32 [%0], {{{",".join(f"%{i + 1}" for i in range(n))}}};" :: "r"(t), {ins});
}}"""


def main() -> None:
    entries, bodies = [], []
    for shape, per, limit in SHAPES:
        for x in reps(limit):
            name = f"{shape.replace('x', '_')}_x{x}"
            bodies.append(kernel(shape, per, x))
            entries.append(f'  {{"{shape}", {x}, {per * x}, {WARP_BYTES[shape] * x}, '
                           f'k_tmem<{per * x}, ld_{name}, st_{name}>}},')
    print(HEAD + "".join(bodies) + KERNEL + "static const Entry ENTRIES[] = {\n"
          + "\n".join(entries) + "\n};\n" + MAIN)


HEAD = r"""// GENERATED by gen_tmem.py; edit the generator, not this file.
// tcgen05.ld / tcgen05.st cost on sm_100a per shape (.32x32b, .16x64b, .16x128b, .16x256b) and repeat .xN.
// One CTA; W warps (1 or 4), each owns its TMEM lane quarter. Each iteration: one ld + wait::ld
// (or st + wait::st). Cycles per op from the slope between two loop lengths; bytes per clock per SM
// from the bytes all warps move per iteration. W=1 gives the dependent round trip (latency).
// Verification: st of known values, then ld back and compare.
// Usage: ./tmem   (JSON lines on stdout)
#include "pb_common.cuh"
#include <cstring>

typedef void (*LdFn)(uint32_t, uint32_t*);
typedef void (*StFn)(uint32_t, const uint32_t*);
"""

KERNEL = r"""

__device__ __forceinline__ void tc_sync() {
  asm volatile("tcgen05.fence::before_thread_sync;");
  __syncthreads();
  asm volatile("tcgen05.fence::after_thread_sync;");
}

// mode 0 = ld timing, 1 = st timing, 2 = verify (st pattern, ld back, report mismatches)
template <int NR, LdFn LD, StFn ST>
__global__ void __launch_bounds__(128, 1) k_tmem(int mode, int iters, uint32_t* out, long long* cyc) {
  __shared__ uint32_t tslot;
  int warp = threadIdx.x / 32;
  if (warp == 0) {
    asm volatile("tcgen05.alloc.cta_group::1.sync.aligned.shared::cta.b32 [%0], 512;" :: "r"(smem_u32(&tslot)));
    asm volatile("tcgen05.relinquish_alloc_permit.cta_group::1.sync.aligned;");
  }
  tc_sync();
  uint32_t t = tslot + ((uint32_t)(warp * 32) << 16);  // each warp may only touch its lane quarter
  uint32_t v[NR];
  for (int i = 0; i < NR; ++i) v[i] = (uint32_t)(threadIdx.x * 1000 + i);
  uint32_t acc = 0;
  tc_sync();
  long long t0 = clock64();
  if (mode == 0) {
    for (int it = 0; it < iters; ++it) {
      LD(t, v);
      asm volatile("tcgen05.wait::ld.sync.aligned;");
      acc ^= v[0];
    }
  } else if (mode == 1) {
    for (int it = 0; it < iters; ++it) {
      asm volatile("" : "+r"(v[0]));
      ST(t, v);
      asm volatile("tcgen05.wait::st.sync.aligned;");
    }
  } else {
    ST(t, v);
    asm volatile("tcgen05.wait::st.sync.aligned;");
    for (int i = 0; i < NR; ++i) v[i] = 0;
    LD(t, v);
    asm volatile("tcgen05.wait::ld.sync.aligned;");
    int bad = 0;
    for (int i = 0; i < NR; ++i) bad += v[i] != (uint32_t)(threadIdx.x * 1000 + i);
    if (bad) atomicAdd(out, 1u);
  }
  __syncthreads();
  long long t1 = clock64();
  if (threadIdx.x == 0) *cyc = t1 - t0;
  if (iters < 0) { out[1] = acc; for (int i = 0; i < NR; ++i) out[2 + i] = v[i]; }  // keep loads live
  tc_sync();
  if (warp == 0) asm volatile("tcgen05.dealloc.cta_group::1.sync.aligned.b32 %0, 512;" :: "r"(tslot));
}

typedef void (*Kern)(int, int, uint32_t*, long long*);
struct Entry { const char* shape; int x; int regs; int warp_bytes; Kern k; };
"""

MAIN = r"""
int main() {
  uint32_t* out; long long* cyc;
  CK(cudaMalloc(&out, 4 * 1024)); CK(cudaMalloc(&cyc, 8));
  const int I1 = 64, I2 = 576;
  for (const Entry& e : ENTRIES) {
    // Verification with 4 warps.
    CK(cudaMemset(out, 0, 4));
    e.k<<<1, 128>>>(2, 1, out, cyc);
    CK(cudaGetLastError()); CK(cudaDeviceSynchronize());
    uint32_t bad; CK(cudaMemcpy(&bad, out, 4, cudaMemcpyDeviceToHost));
    for (int mode = 0; mode < 2; ++mode)
    for (int W : {1, 4}) {
      std::vector<double> per;
      for (int rep = 0; rep < 5; ++rep) {
        double c[2]; int its[2] = {I1, I2};
        for (int x = 0; x < 2; ++x) {
          e.k<<<1, 32 * W>>>(mode, its[x], out, cyc);
          CK(cudaDeviceSynchronize());
          long long h; CK(cudaMemcpy(&h, cyc, 8, cudaMemcpyDeviceToHost));
          c[x] = (double)h;
        }
        per.push_back((c[1] - c[0]) / (I2 - I1));
      }
      double it = median(per);
      Json j; j.s("family", "tmem").s("primitive", mode ? "tcgen05.st" : "tcgen05.ld")
        .s("p.shape", e.shape).i("p.x", e.x).i("p.regs_per_thread", e.regs).i("p.warps", W)
        .i("p.bytes_per_warp", e.warp_bytes)
        .f("m.cyc_per_op", it).f("m.bytes_per_clk_sm", (double)e.warp_bytes * W / it)
        .i("c.ctas", 1).t("verified", bad == 0).i("n_reps", (long long)per.size()).f("cv", cv(per))
        .s("note", "each iteration = one op + tcgen05.wait (the wait makes it a round trip); "
                   "W=1 is the dependent latency, W=4 uses all four TMEM lane quarters");
      j.print();
    }
  }
  return 0;
}
"""


if __name__ == "__main__":
    main()
